#!/usr/bin/env python3
"""Writes harmony/classifymenu/src/main/ets/core/CYLCoreStrings.ets: the core's strings
(CollectionViewClassifyMenu/Resources/Localization/*.lproj/CYLClassifyMenu.strings) for CYLMenuResources.

  export-core-strings.py           write the module
  export-core-strings.py --check   exit 1 when it is out of date

The .strings parser is the one of scripts/export-miniprogram-data.py, so every port reads the same tables.
"""
import importlib.util
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "harmony/classifymenu/src/main/ets/core/CYLCoreStrings.ets"

spec = importlib.util.spec_from_file_location("export_miniprogram_data", ROOT / "scripts/export-miniprogram-data.py")
data = importlib.util.module_from_spec(spec)
spec.loader.exec_module(data)


def module():
    tables = {}
    for path in sorted(data.CORE_STRINGS.glob("*.lproj/CYLClassifyMenu.strings")):
        text = re.sub(r"/\*.*?\*/", "", path.read_text(encoding="utf-8"), flags=re.S)
        tables[path.parent.name[: -len(".lproj")]] = {data.unescape(k): data.unescape(v)
                                                       for k, v in data.STRING_LINE.findall(text)}
    lines = ["// Generated by harmony/scripts/export-core-strings.py from",
             "// CollectionViewClassifyMenu/Resources/Localization/*.lproj/CYLClassifyMenu.strings. Do not edit.", "",
             "/** The core's strings by language, then key. */",
             "export const CYL_CORE_STRINGS: Record<string, Record<string, string>> = {"]
    for language in sorted(tables):
        lines.append("  %s: {" % json.dumps(language))
        for key in sorted(tables[language]):
            lines.append("    %s: %s," % (json.dumps(key), json.dumps(tables[language][key], ensure_ascii=False)))
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = module()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            print("CYLCoreStrings.ets is out of date (run harmony/scripts/export-core-strings.py)")
            return 1
        print("OK: CYLCoreStrings.ets matches the core's strings.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main())
