#!/usr/bin/env python3
"""Writes harmony/entry/src/main/ets/data/CYLExampleStrings.ets: the example's strings
(Example/CYLMenuExample/CYLMenuExample.bundle/*.lproj/Localizable.strings) for CYLExampleLocalizedString, and the
search history and discover demo's data of each language (*.lproj/search-discover.json), as iOS reads them.

  export-example-strings.py           write the module
  export-example-strings.py --check   exit 1 when it is out of date

The keys are the Simplified Chinese text, as on iOS; zh-Hans therefore needs no table of its own.
"""
import importlib.util
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "Example/CYLMenuExample/CYLMenuExample.bundle"
OUT = ROOT / "harmony/entry/src/main/ets/data/CYLExampleStrings.ets"

spec = importlib.util.spec_from_file_location("export_miniprogram_data", ROOT / "scripts/export-miniprogram-data.py")
data = importlib.util.module_from_spec(spec)
spec.loader.exec_module(data)


def module():
    tables = {}
    for path in sorted(SOURCE.glob("*.lproj/Localizable.strings")):
        text = re.sub(r"/\*.*?\*/", "", path.read_text(encoding="utf-8"), flags=re.S)
        tables[path.parent.name[: -len(".lproj")]] = {data.unescape(k): data.unescape(v)
                                                       for k, v in data.STRING_LINE.findall(text)}
    lines = ["// Generated by harmony/scripts/export-example-strings.py from",
             "// Example/CYLMenuExample/CYLMenuExample.bundle/*.lproj/Localizable.strings. Do not edit.", "",
             "/** The example's strings by language, then key (the Simplified Chinese text). */",
             "export const CYL_EXAMPLE_STRINGS: Record<string, Record<string, string>> = {"]
    for language in sorted(tables):
        lines.append("  %s: {" % json.dumps(language))
        for key in sorted(tables[language]):
            lines.append("    %s: %s," % (json.dumps(key, ensure_ascii=False),
                                         json.dumps(tables[language][key], ensure_ascii=False)))
        lines.append("  },")
    lines.append("};")
    lines += ["", "/** search-discover.json of each language (the same topics in the same order), as JSON text. */",
              "export const CYL_SEARCH_DISCOVER_JSON: Record<string, string> = {"]
    for path in sorted(SOURCE.glob("*.lproj/search-discover.json")):
        compact = json.dumps(json.loads(path.read_text(encoding="utf-8")), ensure_ascii=False, separators=(",", ":"))
        lines.append("  %s: %s," % (json.dumps(path.parent.name[: -len(".lproj")]), json.dumps(compact, ensure_ascii=False)))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = module()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            print("CYLExampleStrings.ets is out of date (run harmony/scripts/export-example-strings.py)")
            return 1
        print("OK: CYLExampleStrings.ets matches the example's strings.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main())
