#!/usr/bin/env python3
"""
Exports the shared example data to the WeChat Mini Program example (CrossPlatform/wechat-miniprogram):

- the places of Example-Shared/Database/cyl_places.sqlite -> miniprogram/data/places.js
- the Lottie tab icons of the Flutter example (CYLTabBarController's tab icons) -> miniprogram/data/lottie/<name>.js

    scripts/export-miniprogram-data.py           write the modules
    scripts/export-miniprogram-data.py --check   exit 1 when a committed module differs from its source

A Mini Program has no SQLite and can `require` only JavaScript, so it reads the rows of the one shared database file
(docs/cross-platform.md) as a module made from that file, and runs the same statement on them in JavaScript
(miniprogram/utils/places-db.js). The rows keep the database order (id).
"""
import json
import pathlib
import re
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DATABASE = ROOT / "Example-Shared/Database/cyl_places.sqlite"
LOTTIE = ROOT / "flutter/cyl_tag_list/example/assets"
OUT = ROOT / "CrossPlatform/wechat-miniprogram/miniprogram/data"
# The core strings ship in the npm library (cyl-tag-list-miniprogram), relative to OUT.
PACKAGE_CORE_TABLES = "../../packages/cyl-tag-list-miniprogram/miniprogram_dist/core-tables.js"
HEADER = "// Generated by scripts/export-miniprogram-data.py from {source}. Do not edit.\n"


def places_module():
    db = sqlite3.connect(f"file:{DATABASE}?mode=ro", uri=True)
    rows = db.execute("SELECT id, name, category, tag, region, rating, price FROM places ORDER BY id").fetchall()
    db.close()
    keys = ["id", "name", "category", "tag", "region", "rating", "price"]
    lines = [json.dumps(dict(zip(keys, row)), ensure_ascii=False) for row in rows]
    source = DATABASE.relative_to(ROOT).as_posix()
    return HEADER.format(source=source) + "module.exports = [\n  " + ",\n  ".join(lines) + "\n];\n"


def lottie_modules():
    for path in sorted(LOTTIE.glob("tab_*_animate.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        name = path.stem.replace("tab_", "").replace("_animate", "")
        yield f"lottie/{name}.js", HEADER.format(source=path.relative_to(ROOT).as_posix()) + f"module.exports = {body};\n"


STRINGS = ROOT / "Example/CYLMenuExample/CYLMenuExample.bundle"
STRING_LINE = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', re.M)


def unescape(text):
    return json.loads(f'"{text}"')


def strings_module():
    """
    The iOS example's strings (CYLMenuExample.bundle/<language>.lproj/Localizable.strings, keyed by the Chinese
    source text), for the Mini Program's t() (miniprogram/utils/i18n.js), the counterpart of CYLExampleLocalizedString.
    """
    tables = {}
    for path in sorted(STRINGS.glob("*.lproj/Localizable.strings")):
        language = path.parent.name[: -len(".lproj")]
        text = path.read_text(encoding="utf-8")
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        tables[language] = {unescape(k): unescape(v) for k, v in STRING_LINE.findall(text)}
    body = json.dumps(tables, ensure_ascii=False, indent=1, sort_keys=True)
    source = STRINGS.relative_to(ROOT).as_posix() + "/*.lproj/Localizable.strings"
    return HEADER.format(source=source) + f"module.exports = {body};\n"


def reviews_module():
    """
    The menu example's reviews of the shared database (tables reviews, review_keywords; CYLReviewStore.mockReviews()
    in the same order): [{id, user, text, date, sku, rating (0 good, 1 neutral, 2 bad), hasPhoto, hasFollowUp,
    keywords}].
    """
    db = sqlite3.connect(f"file:{DATABASE}?mode=ro", uri=True)
    rows = db.execute("SELECT id, user, text, date, sku, rating, has_photo, has_follow_up FROM reviews ORDER BY id").fetchall()
    keywords = {}
    for review_id, keyword in db.execute("SELECT review_id, keyword FROM review_keywords ORDER BY rowid"):
        keywords.setdefault(review_id, []).append(keyword)
    db.close()
    lines = [json.dumps({"id": r[0], "user": r[1], "text": r[2], "date": r[3], "sku": r[4], "rating": r[5],
                         "hasPhoto": bool(r[6]), "hasFollowUp": bool(r[7]), "keywords": keywords.get(r[0], [])},
                        ensure_ascii=False) for r in rows]
    source = DATABASE.relative_to(ROOT).as_posix()
    return HEADER.format(source=source) + "module.exports = [\n  " + ",\n  ".join(lines) + "\n];\n"


CORE_STRINGS = ROOT / "CollectionViewClassifyMenu/Resources/Localization"


def core_strings_module():
    """
    The core library's strings (CYLClassifyMenu.strings, keyed by identifiers such as CYLMenuExpand), for tc() in
    the npm library's locale.js (packages/cyl-tag-list-miniprogram), the counterpart of CYLMenuLocalizedString.
    """
    tables = {}
    for path in sorted(CORE_STRINGS.glob("*.lproj/CYLClassifyMenu.strings")):
        text = re.sub(r"/\*.*?\*/", "", path.read_text(encoding="utf-8"), flags=re.S)
        tables[path.parent.name[: -len(".lproj")]] = {unescape(k): unescape(v) for k, v in STRING_LINE.findall(text)}
    body = json.dumps(tables, ensure_ascii=False, indent=1, sort_keys=True)
    source = CORE_STRINGS.relative_to(ROOT).as_posix() + "/*.lproj/CYLClassifyMenu.strings"
    return HEADER.format(source=source) + f"module.exports = {body};\n"


CLASSIFY_DATA = ROOT / "CollectionViewClassifyMenu/Class/Other/data.json"


def classify_menu_module():
    """
    The classify menu's data (data.json, CYLDBManager.dataSource()): [{title, items: [{title, picture}]}], picture
    being whether the tag shows the star image (home_btn_shrink), as CYLDemoDataSource.classifyDataSource() reads it.
    data.json is not strict JSON (trailing commas), so they are dropped first.
    """
    text = re.sub(r",(\s*[}\]])", r"\1", CLASSIFY_DATA.read_text(encoding="utf-8"))
    sections = [{"title": s["Type"], "items": [{"title": i["Item_Title"], "picture": bool(i.get("Picture"))}
                                               for i in s["Items"]]} for s in json.loads(text)]
    body = json.dumps(sections, ensure_ascii=False, indent=1)
    return HEADER.format(source=CLASSIFY_DATA.relative_to(ROOT).as_posix()) + f"module.exports = {body};\n"


def modules():
    yield "places.js", places_module()
    yield "classify-menu.js", classify_menu_module()
    yield PACKAGE_CORE_TABLES, core_strings_module()
    yield "reviews.js", reviews_module()
    yield "strings.js", strings_module()
    yield from lottie_modules()


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in modules():
        target = (OUT / name).resolve()
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(name)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target.relative_to(ROOT).as_posix()}")
    if stale:
        print("Out of date (run scripts/export-miniprogram-data.py):", ", ".join(stale))
        sys.exit(1)
    if check:
        print("OK: the Mini Program data matches its sources.")


if __name__ == "__main__":
    main()
