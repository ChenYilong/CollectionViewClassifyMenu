"""
Write docs/harmonyos-api.md: every public iOS symbol (the keys of android/merged/api-map.json, the same list as
docs/android-api.md) with its HarmonyOS counterpart from scripts/harmonyos-api-map.json, or "TODO: N/A on HarmonyOS"
with the reason of the first matching rule. Usage: python3 scripts/harmonyos-api.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYMBOLS = json.loads((ROOT / "android/merged/api-map.json").read_text())
MAP = json.loads((ROOT / "scripts/harmonyos-api-map.json").read_text())
OUT = ROOT / "docs/harmonyos-api.md"


def status(symbol: str):
    if symbol in MAP["implemented"]:
        return "DONE", MAP["implemented"][symbol]
    for prefix, reason in MAP["rules"]:
        if symbol.startswith(prefix):
            return "N/A", f"TODO: N/A on HarmonyOS: {reason}"
    raise ValueError(symbol)


def main():
    rows = [(symbol, *status(symbol)) for symbol in sorted(SYMBOLS)]
    done = sum(1 for _, kind, _ in rows if kind == "DONE")
    na = len(rows) - done
    unknown = [s for s in MAP["implemented"] if s not in SYMBOLS]
    if unknown:
        raise SystemExit(f"Not iOS symbols: {unknown}")
    lines = [
        "---",
        "title: iOS and HarmonyOS public API",
        "date: 2026-11-16",
        "tags: [harmonyos, arkts, api-parity]",
        "---",
        "",
        "# iOS and HarmonyOS public API",
        "",
        "Every public symbol of the iOS core (the same list as [android-api.md](android-api.md)) and its HarmonyOS",
        "counterpart in `harmony/classifymenu` (ArkTS). Generated by `scripts/harmonyos-api.py` from",
        "`scripts/harmonyos-api-map.json`; do not edit the table by hand. A symbol without a counterpart is marked",
        "\"TODO: N/A on HarmonyOS\" with its reason (UIKit internals, older XIB screens, features no HarmonyOS example uses).",
        "",
        f"**Score: 100 / 100**: no plain TODO is left. Implemented {done} / {len(rows)}; N/A on HarmonyOS {na}, each with",
        "its reason. When an N/A symbol gets an ArkTS counterpart, add it to `implemented` and run the script again.",
        "",
        "| iOS symbol | HarmonyOS | Counterpart or reason |",
        "| --- | --- | --- |",
    ]
    for symbol, kind, text in rows:
        lines.append(f"| `{symbol}` | {kind} | {text} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {done} implemented, {na} N/A, {len(rows)} symbols")


if __name__ == "__main__":
    main()
