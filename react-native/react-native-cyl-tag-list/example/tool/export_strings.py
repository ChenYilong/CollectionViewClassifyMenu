#!/usr/bin/env python3
"""Writes src/dataStrings.ts: the shared demo data's titles (dishes, regions, categories, the sample suffix word) in
English and Traditional Chinese, read from the iOS example bundle
(Example/CYLMenuExample/CYLMenuExample.bundle/<language>.lproj/Localizable.strings), so every platform shows the same
words. Keys are the source titles (Simplified Chinese) that data.json and the places database keep; Simplified
Chinese shows the key. Usage: python3 react-native/react-native-cyl-tag-list/example/tool/export_strings.py [--check]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
BUNDLE = ROOT / 'Example/CYLMenuExample/CYLMenuExample.bundle'
OUT = pathlib.Path(__file__).resolve().parents[1] / 'src/dataStrings.ts'
LINE = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', re.M)
# The keys of the iOS bundle's demo data section ("Demo data (data.json and the places database keep these source
# titles) ..."), plus the separator of a list of names.
SECTION = 'Demo data (data.json and the places database keep these source titles)'


def table(language):
    return (BUNDLE / f'{language}.lproj/Localizable.strings').read_text(encoding='utf-8')


def keys():
    text = table('en')
    start = text.index(SECTION)
    block = text[start:text.find('/*', start + len(SECTION))] if '/*' in text[start + len(SECTION):] else text[start:]
    return [k for k, _ in LINE.findall(block)] + ['、']


def values(language):
    text = re.sub(r'/\*.*?\*/', '', table(language), flags=re.S)
    return dict(LINE.findall(text))


def module():
    names = keys()
    lines = ['// Generated by tool/export_strings.py from the iOS example bundle. Do not edit.', '',
             '/**', ' * The shared demo data\'s titles by language, then source title (Simplified Chinese shows the key).',
             ' */', 'export const DATA_STRINGS: Record<string, Record<string, string>> = {']
    for language in ('en', 'zh-Hant'):
        found = values(language)
        missing = [k for k in names if k not in found]
        if missing:
            raise SystemExit(f'not in the iOS {language} bundle: {missing}')
        lines.append(f"  '{language}': {{")
        lines += [f'    {json.dumps(k, ensure_ascii=False)}: {json.dumps(found[k], ensure_ascii=False)},' for k in names]
        lines.append('  },')
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    text = module()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            raise SystemExit(f'{OUT.relative_to(ROOT)} is out of date: run tool/export_strings.py')
        print('OK: src/dataStrings.ts matches the iOS strings.')
        return
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
