#!/usr/bin/env python3
"""
Exports the iOS example's animated and static tag icons to the Mini Program (miniprogram/data/animations and
miniprogram/images/styles), for the Styles, Animated icons and Configuration screens:

- Lottie files of Example/CYLMenuExample/CYLMenuExample.bundle/Animations/Lottie -> data/animations/lottie/<name>.js
  (a Mini Program can `require` only JavaScript; image assets are embedded as data URIs). The four tab_*_animate.json
  files are the ones of data/lottie/*.js (scripts/export-miniprogram-data.py), so the registry reuses those modules.
- GIF files -> data/animations/gif/<name>.gif, with the first and last frames as PNG (the resting and the selected
  frame: an <image> plays a GIF on its own) and the duration of one pass.
- the configuration file Configurations/animated-tags.json, copied as is.
- CYLTabBarController's tab images and the Lottie placeholders of Assets.xcassets -> images/styles/tab/<name>.png.
- data/animations/index.js: the registry, by the path the iOS example uses ("Lottie/tab_home_animate.json").

    python3 scripts/export-animations.py           write the files
    python3 scripts/export-animations.py --check   exit 1 when a written file differs from its source

Needs Pillow (the GIF frames).
"""
import base64
import io
import json
import pathlib
import sys

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parents[1]
ROOT = HERE.parents[1]
BUNDLE = ROOT / "Example/CYLMenuExample/CYLMenuExample.bundle"
ASSETS = ROOT / "Example/CYLMenuExample/Assets.xcassets"
OUT = HERE / "miniprogram/data/animations"
IMAGES = HERE / "miniprogram/images/styles/tab"
HEADER = "// Generated by scripts/export-animations.py from {source}. Do not edit.\n"

# The tab_*_animate.json files, already exported to data/lottie/<name>.js.
SHARED_LOTTIE = {
    "tab_home_animate.json": "home",
    "tab_message_animate.json": "message",
    "tab_search_animate.json": "search",
    "tab_me_animate.json": "me",
}
LOTTIE = [
    "gray_tabbar_home_animation.json", "gray_tabbar_message_animation.json", "gray_tabbar_me_animation.json",
    "green_lottie_tab_home.json", "green_lottie_tab_news.json", "green_lottie_tab_discover.json",
    "green_lottie_tab_mine.json",
]
GIFS = ["tab_fire.gif", "tab_rocket.gif", "tab_star.gif", "cyl_tab_sample_animated.gif"]
TAB_IMAGES = [
    "home_normal", "home_highlight", "fishpond_normal", "fishpond_highlight", "post_normal", "post_highlight",
    "message_normal", "message_highlight", "account_normal", "account_highlight",
    "gray_tabbar_home_animation_lottie_placeholder", "gray_tabbar_message_animation_lottie_placeholder",
    "gray_tabbar_me_animation_lottie_placeholder",
]


def rel(path):
    return path.relative_to(ROOT).as_posix()


def lottie_module(name):
    path = BUNDLE / "Animations/Lottie" / name
    data = json.loads(path.read_text(encoding="utf-8"))
    for asset in data.get("assets", []):
        if not asset.get("p") or asset.get("e") == 1:
            continue
        # Image assets come from the app's asset catalog (LottieImages/<name>.imageset) on iOS.
        image = next(ASSETS.glob(f"**/{pathlib.Path(asset['p']).stem}.imageset/{asset['p']}"))
        asset["u"] = ""
        asset["p"] = "data:image/png;base64," + base64.b64encode(image.read_bytes()).decode("ascii")
        asset["e"] = 1
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return HEADER.format(source=rel(path)) + f"module.exports = {body};\n"


def png(image):
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def gif_files(name):
    path = BUNDLE / "Animations/GIF" / name
    image = Image.open(path)
    durations = []
    first = None
    last = None
    index = 0
    while True:
        durations.append(image.info.get("duration") or 100)
        frame = image.convert("RGBA")
        if first is None:
            first = frame
        last = frame
        index += 1
        try:
            image.seek(index)
        except EOFError:
            break
    stem = path.stem
    meta = {"width": image.size[0], "height": image.size[1], "duration": sum(durations), "frames": len(durations)}
    return stem, meta, {
        f"gif/{name}": path.read_bytes(),
        f"gif/{stem}.first.png": png(first),
        f"gif/{stem}.last.png": png(last),
    }


def tab_image(name):
    folder = next(ASSETS.glob(f"**/{name}.imageset"))
    contents = json.loads((folder / "Contents.json").read_text(encoding="utf-8"))
    files = [entry for entry in contents["images"] if entry.get("filename") and not entry.get("appearances")]
    # The largest scale: the Mini Program draws it at the tag's imageSize.
    files.sort(key=lambda entry: entry.get("scale", "1x"))
    return (folder / files[-1]["filename"]).read_bytes()


def outputs():
    """{path: bytes} of every file this script writes."""
    files = {}
    registry = {}
    for name, module in SHARED_LOTTIE.items():
        registry[f"Lottie/{name}"] = ("lottie", f"require('../lottie/{module}.js')")
    for name in LOTTIE:
        stem = pathlib.Path(name).stem
        files[OUT / f"lottie/{stem}.js"] = lottie_module(name).encode("utf-8")
        registry[f"Lottie/{name}"] = ("lottie", f"require('./lottie/{stem}.js')")
    gifs = {}
    for name in GIFS:
        stem, meta, gif = gif_files(name)
        for path, data in gif.items():
            files[OUT / path] = data
        gifs[f"GIF/{name}"] = {
            "engine": "gif",
            "src": f"/data/animations/gif/{name}",
            "first": f"/data/animations/gif/{stem}.first.png",
            "last": f"/data/animations/gif/{stem}.last.png",
            **meta,
        }
    # Rive files as *.riv.bin (a code package leaves out .riv files), played by CYLTabBarController's cyl-rive.
    rives = {}
    for path in sorted((BUNDLE / "Animations/Rive").glob("*.riv")):
        files[OUT / f"rive/{path.name}.bin"] = path.read_bytes()
        rives[f"Rive/{path.name}"] = {"engine": "rive", "src": f"/data/animations/rive/{path.name}.bin"}
    # PAG files: fetched (not in the repository) and copied to the engines subpackage by scripts/fetch-cyltabbar.js;
    # the registry lists the pinned names of Example-Shared/PAGResources/pag-resources.json.
    manifest = json.loads((ROOT / "Example-Shared/PAGResources/pag-resources.json").read_text(encoding="utf-8"))
    pags = {}
    for entry in manifest["files"]:
        name = pathlib.PurePosixPath(entry.get("file") or entry["path"]).name
        if name.endswith(".pag"):
            pags[f"pag-ios/{name}"] = {"engine": "pag", "src": f"/engines/pag/{name}.bin"}
    configuration = BUNDLE / "Configurations/animated-tags.json"
    files[OUT / "Configurations/animated-tags.json"] = configuration.read_bytes()
    for name in TAB_IMAGES:
        files[IMAGES / f"{name}.png"] = tab_image(name)

    lines = [HEADER.format(source=rel(BUNDLE / "Animations")).rstrip("\n"),
             "/**",
             " * The animated icons of the iOS example (CYLMenuExample.bundle/Animations), by the path the iOS example uses",
             " * (\"Lottie/tab_home_animate.json\"). A Lottie entry loads its data on first use (`data()`); a GIF entry has",
             " * the file, its first and last frames and the duration of one pass in milliseconds; a Rive entry has its",
             " * .riv.bin file. PAG files are not here: their engine is not in the package (cyl-tag-list/animations.js).",
             " */",
             "module.exports = {"]
    for key, (engine, loader) in registry.items():
        lines.append(f"  {json.dumps(key)}: {{ engine: '{engine}', data: () => {loader} }},")
    for key, entry in list(gifs.items()) + list(rives.items()) + list(pags.items()):
        lines.append(f"  {json.dumps(key)}: {json.dumps(entry, ensure_ascii=False)},")
    lines.append("};")
    files[OUT / "index.js"] = ("\n".join(lines) + "\n").encode("utf-8")
    return files


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, data in outputs().items():
        if check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(path.relative_to(HERE).as_posix())
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    if stale:
        print("Stale (run scripts/export-animations.py):\n  " + "\n  ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
