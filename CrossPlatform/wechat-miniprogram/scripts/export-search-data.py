#!/usr/bin/env python3
"""
Exports the data of the search discover screen (CYLSearchDiscoverViewController) to the Mini Program:

- Example/CYLMenuExample/CYLMenuExample.bundle/<language>.lproj/search-discover.json (one file per language, the
  same topics in the same order) -> miniprogram/data/search/search-discover.js, keyed by "zh-Hans", "zh-Hant", "en"
  (a Mini Program can only `require` JavaScript);
- the localized hot icon <language>.lproj/discover-hot@3x.png -> miniprogram/images/search/discover-hot-<language>.png;
- the core's template images, tinted as the iOS screen tints them: cyl_more@3x.png (the More button,
  secondaryLabel) -> images/search/more.png, cyl_fold_chevron@3x.png (the inline fold cell, CYLMenuStyle
  foldControlColor = UIColor.gray) -> images/search/fold-chevron.png.

Run from anywhere: python3 CrossPlatform/wechat-miniprogram/scripts/export-search-data.py [--check]
--check fails (exit 1) when an exported file differs from what the sources give. Needs Pillow for the tinted images.
"""
import io
import json
import shutil
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
REPO = PROJECT.parent.parent
BUNDLE = REPO / "Example" / "CYLMenuExample" / "CYLMenuExample.bundle"
ASSETS = REPO / "CollectionViewClassifyMenu" / "Class" / "Other" / "Symtem" / "Images.xcassets"
DATA_OUT = PROJECT / "miniprogram" / "data" / "search" / "search-discover.js"
IMAGES_OUT = PROJECT / "miniprogram" / "images" / "search"
LANGUAGES = ["zh-Hans", "zh-Hant", "en"]

# (source image set, output name, RGBA tint): UIColor.secondaryLabel and UIColor.gray.
TINTED = [
    ("cyl_more", "more.png", (60, 60, 67, 153)),
    ("cyl_fold_chevron", "fold-chevron.png", (128, 128, 128, 255)),
]


def data_module():
    tables = {}
    for language in LANGUAGES:
        data = json.loads((BUNDLE / f"{language}.lproj" / "search-discover.json").read_text(encoding="utf-8"))
        data.pop("comment", None)
        tables[language] = data
    body = json.dumps(tables, ensure_ascii=False, indent=1)
    return (
        "// Generated by scripts/export-search-data.py from Example/CYLMenuExample/CYLMenuExample.bundle/"
        "*.lproj/search-discover.json. Do not edit.\n"
        f"module.exports = {body};\n"
    ).encode("utf-8")


def tinted_png(source, color):
    from PIL import Image

    image = Image.open(source).convert("RGBA")
    r, g, b, a = color
    alpha = image.getchannel("A").point(lambda value: value * a // 255)
    result = Image.new("RGBA", image.size, (r, g, b, 0))
    result.putalpha(alpha)
    out = io.BytesIO()
    result.save(out, format="PNG", optimize=True)
    return out.getvalue()


def outputs():
    """Every exported file: {path: bytes}."""
    files = {DATA_OUT: data_module()}
    for language in LANGUAGES:
        files[IMAGES_OUT / f"discover-hot-{language}.png"] = (BUNDLE / f"{language}.lproj" / "discover-hot@3x.png").read_bytes()
    for name, output, color in TINTED:
        files[IMAGES_OUT / output] = tinted_png(ASSETS / f"{name}.imageset" / f"{name}@3x.png", color)
    return files


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_bytes() != content:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        print(f"wrote {path.relative_to(PROJECT)} ({len(content)} bytes)")
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(PROJECT)}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
