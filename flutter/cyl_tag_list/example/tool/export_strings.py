#!/usr/bin/env python3
"""Writes lib/strings.dart: the iOS example strings the Flutter example shows, in en, zh-Hans and zh-Hant.

The keys are the iOS example's (its Simplified Chinese text), read from
Example/CYLMenuExample/CYLMenuExample.bundle/<language>.lproj/Localizable.strings, so every platform shows the same
words. Usage: python3 flutter/cyl_tag_list/example/tool/export_strings.py [--check]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
BUNDLE = ROOT / 'Example/CYLMenuExample/CYLMenuExample.bundle'
OUT = pathlib.Path(__file__).resolve().parents[1] / 'lib/strings.dart'
KEYS = ['动效图标', '倍速', '循环播放', '全部播放', '从头播放屏幕上的全部动效', '全部', '重置', '多选筛选',
        '没有符合条件的商家', '分类：%@ · 地区：%@ · 菜品：%@', '匹配 %lu 条', '分类菜单 + 多选筛选 · 数据库联动', '确定', '取消', '点击「%@」', '菜单', '菜单选择 · 数据库联动']
LINE = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', re.M)


def table(language):
    text = re.sub(r'/\*.*?\*/', '', (BUNDLE / f'{language}.lproj/Localizable.strings').read_text(encoding='utf-8'),
                  flags=re.S)
    return {k.replace('\\"', '"'): v.replace('\\"', '"') for k, v in LINE.findall(text)}


def module():
    en, hant = table('en'), table('zh-Hant')
    missing = [k for k in KEYS if k not in en]
    if missing:
        raise SystemExit(f'not in the iOS bundle: {missing}')
    lines = ['// Generated by tool/export_strings.py from the iOS example bundle. Do not edit.', '',
             "import 'dart:ui';", '',
             '/// The iOS example strings this example shows, by language, then key (the Simplified Chinese text).',
             'const Map<String, Map<String, String>> _strings = {']
    for language, values in (('en', en), ('zh-Hant', hant)):
        lines.append(f"  '{language}': {{")
        for key in KEYS:
            lines.append(f'    {json.dumps(key, ensure_ascii=False)}: {json.dumps(values.get(key, key), ensure_ascii=False)},')
        lines.append('  },')
    lines += ['};', '',
              '/// `en`, `zh-Hans` or `zh-Hant` for [locale], as iOS picks among the example bundle\'s `.lproj` folders.',
              'String cylLanguage(Locale locale) {',
              "  if (locale.languageCode != 'zh') return 'en';",
              "  final script = locale.scriptCode ?? '';",
              "  final region = locale.countryCode ?? '';",
              "  return script == 'Hant' || const ['TW', 'HK', 'MO'].contains(region) ? 'zh-Hant' : 'zh-Hans';",
              '}', '',
              '/// The string of [key] in the device language; `%@`, `%d`, `%ld`, `%lu` take [args] in order.',
              'String cylString(String key, [List<Object> args = const [], Locale? locale]) {',
              '  final language = cylLanguage(locale ?? PlatformDispatcher.instance.locale);',
              "  var text = language == 'zh-Hans' ? key : (_strings[language]?[key] ?? key);",
              '  var index = 0;',
              "  return text.replaceAllMapped(RegExp(r'%(@|lu|ld|d)'), (match) => index < args.length ? '${args[index++]}' : match[0]!);",
              '}', '']
    return '\n'.join(lines)


def main():
    text = module()
    if '--check' in sys.argv[1:]:
        current = OUT.read_text(encoding='utf-8').replace('\r\n', '\n') if OUT.exists() else ''
        if current != text:
            print('lib/strings.dart is out of date (run tool/export_strings.py)')
            return 1
        print('OK: lib/strings.dart matches the iOS strings.')
        return 0
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', OUT.relative_to(ROOT).as_posix())
    return 0


if __name__ == '__main__':
    sys.exit(main())
